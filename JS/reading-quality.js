    if(/一生|終身|全生涯|歷年|所有大運|全部大限|出生到現在/.test(q))return {mode:'all',start:null,end:null};
    var years=(q.match(/(?:18|19|20|21)\d{2}/g)||[]).map(Number);
    if(/去年/.test(q))years.push(y-1);
