'use strict';
// The canonical public-domain Chinese text retains per-page revision provenance.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const base=path.resolve(__dirname,'..'),core=require(path.join(base,'JS/liuyao-core.js'));
const data=JSON.parse(fs.readFileSync(path.join(base,'data/yijing-source.json'),'utf8'));
assert.equal(data.entries.length,64);
const lookup=Array.from({length:64},(_,i)=>core.hexagram(i));
data.entries.forEach((e,i)=>{
  assert.equal(e.number,i+1);assert.equal(e.lines.length,6);assert(e.judgment&&e.image&&e.source&&e.revision);
  const g=lookup.find(g=>g.number===e.number);assert.equal(g.name,e.name);
  e.lines.forEach((l,j)=>{assert(l.text);assert.equal(l.label.includes('九'),!!g.lines[j],e.name+' '+l.label);});
  assert.equal(!!e.use,e.number<3);
});
const target=path.join(base,'JS/yijing-data.js'),content='// GENERATED by scripts/build-yijing-data.cjs. Text provenance: data/yijing-source.json.\n'+
 '(function(root){"use strict";var data='+JSON.stringify(data)+';function freeze(x){if(x&&typeof x==="object"){Object.keys(x).forEach(function(k){freeze(x[k]);});Object.freeze(x);}return x;}root.JYYijingData=freeze(data);})(typeof window!=="undefined"?window:globalThis);\n';
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(target,'utf8'),content,'Stale Yijing data');
else fs.writeFileSync(target,content);
console.log('Yijing: 64 judgments, 384 yao, 2 uses, exact source labels and revisions verified.');
